"""Make trip413_frames.h: 150 ms frames rebuilt from Trip 413 samples 2440-2462 for drowsiness_test.cpp.

Trip 413 = DrowsyFW 0.3.3-visible, 18-19 Oct 2026. The user walked away: every sample here is "not visible",
yet unseen frames gave closed_ms peaks 1016 -> 1351 -> 2851 ms, so level 2 entered at sample 2451 and stayed
latched 3294 s with no eyes seen (the only release was 1 s of open eyes).

Same method as make_trip412_frames.py: reconstruct_trip.cpp --lookahead, built against the 0.3.3 judge
(commit b6c363a, the rules on the board), picks the frames with the least visible evidence that reproduce
the board's closed_ms peaks. drowsiness_test.cpp appends 3294 s of "not visible" and checks the release.

  python make_trip413_frames.py      (needs git + MinGW g++; writes trip413_frames.h)
"""
import json, os, subprocess, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
GXX = r"C:\ProgramData\mingw64\mingw64\bin\g++.exe"
OLD = "b6c363a"
E = {0: ".", 1: "O", 2: "C", 3: "u", 4: "."}

d = json.load(open(os.path.join(HERE, "trip413_samples.json")))
lines, prev = [], None
for s in d["samples"]:
    n = 7 if prev is None else max(1, round((s[1] - prev) / 150))
    prev = s[1]
    lines.append(f"{n} {E[s[2]]} {s[9]}")

with tempfile.TemporaryDirectory() as tmp:
    for f in ("drowsiness.cpp", "drowsiness.h", "drowsy_config.h", "domain_types.h"):
        src = subprocess.run(["git", "show", f"{OLD}:firmware/DrowsyFW/{f}"], cwd=HERE, check=True,
                             capture_output=True).stdout
        open(os.path.join(tmp, f), "wb").write(src)
    exe = os.path.join(tmp, "reconstruct.exe")
    subprocess.run([GXX, "-std=c++17", "-O2", "-I", tmp, os.path.join(HERE, "reconstruct_trip.cpp"),
                    os.path.join(tmp, "drowsiness.cpp"), "-o", exe], check=True)
    r = subprocess.run([exe, "--lookahead"], input="\n".join(lines) + "\n", capture_output=True, text=True, check=True)
    frames = r.stdout.strip()
    print(r.stderr.strip())

with open(os.path.join(HERE, "trip413_frames.h"), "w", newline="\n") as f:
    f.write("// generated by make_trip413_frames.py from trip413_samples.json - do not edit\n")
    f.write(f"// {len(d['samples'])} samples -> {len(frames)} frames of 150 ms - O open, C closed, u uncertain, . not visible\n")
    f.write("#pragma once\nstatic const char TRIP413_FRAMES[] =\n")
    for k in range(0, len(frames), 100):
        f.write(f'  "{frames[k:k + 100]}"\n')
    f.write(";\n")
print("wrote trip413_frames.h")
