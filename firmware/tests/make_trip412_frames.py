"""Make trip412_frames.h: 150 ms frames rebuilt from Trip 412 (22:12:00-22:15:00) for drowsiness_test.cpp.

Trip 412 = DrowsyFW 0.3.2-closedev on 18 Oct 2026. In this window the driver was doing homework / using a
phone (looking down, eyes open). The face was lost most of the time, with sparse Closed frames (the eye
model reads downward gaze as closed), yet the board raised Microsleep at 22:12:43 and 22:14:20
(closed_ms peaks 5253 and 7703 ms).

Input: trip412_samples.json = samples 3143-3323 of GET /api/trips/412 (same cols as Trip 411, see
make_trip411_frames.py). Same method as Trip 411: reconstruct_trip.cpp, built against the 0.3.2 judge
(commit 50d2e70, the rules on the board), picks the frames with the least visible evidence that make that
judge reproduce the board's closed_ms peaks. The new judge is then tested on those frames.

  python make_trip412_frames.py      (needs git + MinGW g++; writes trip412_frames.h)
"""
import json, os, subprocess, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
GXX = r"C:\ProgramData\mingw64\mingw64\bin\g++.exe"
OLD = "50d2e70"
E = {0: ".", 1: "O", 2: "C", 3: "u", 4: "."}

d = json.load(open(os.path.join(HERE, "trip412_samples.json")))
lines, prev = [], None
for s in d["samples"]:
    n = 7 if prev is None else max(1, round((s[1] - prev) / 150))
    prev = s[1]
    lines.append(f"{n} {E[s[2]]} {s[9]}")

with tempfile.TemporaryDirectory() as tmp:
    for f in ("drowsiness.cpp", "drowsiness.h", "drowsy_config.h", "domain_types.h"):
        src = subprocess.run(["git", "show", f"{OLD}:firmware/DrowsyFW/{f}"], cwd=HERE, check=True,
                             capture_output=True).stdout
        open(os.path.join(tmp, f), "wb").write(src)
    exe = os.path.join(tmp, "reconstruct.exe")
    subprocess.run([GXX, "-std=c++17", "-O2", "-I", tmp, os.path.join(HERE, "reconstruct_trip.cpp"),
                    os.path.join(tmp, "drowsiness.cpp"), "-o", exe], check=True)
    r = subprocess.run([exe, "--lookahead"], input="\n".join(lines) + "\n", capture_output=True, text=True, check=True)
    frames = r.stdout.strip()
    print(r.stderr.strip())

with open(os.path.join(HERE, "trip412_frames.h"), "w", newline="\n") as f:
    f.write("// generated by make_trip412_frames.py from trip412_samples.json - do not edit\n")
    f.write(f"// {len(d['samples'])} samples -> {len(frames)} frames of 150 ms - O open, C closed, u uncertain, . not visible\n")
    f.write("#pragma once\nstatic const char TRIP412_FRAMES[] =\n")
    for k in range(0, len(frames), 100):
        f.write(f'  "{frames[k:k + 100]}"\n')
    f.write(";\n")
print("wrote trip412_frames.h")
