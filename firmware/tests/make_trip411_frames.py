"""Make trip411_frames.h: 150 ms frames rebuilt from Trip 411 for drowsiness_test.cpp.

Trip 411 = DrowsyFW 0.3.1 on 18 Oct 2026 (~22 min). The driver was at the PC, not facing the camera
(face in ~24% of samples, 68 Distraction events), yet the board logged 2 Microsleeps (~195 s, ~445 s).

Input: trip411_samples.json = GET /api/trips/411?from=0&count=2000&step=1
  cols [i, ms, eye(1 open, 2 closed, 3 uncertain, 4 not visible), level, flags, p_closed permille,
        perclos permille, fps10, ldr, closed_ms] - eye is the state at the sample instant,
        closed_ms is the PEAK closed run since the previous sample.

Frames were not logged, so they are rebuilt: sample i covers (ms[i-1], ms[i]] = round(dt/150) frames
(~7 per second, ~16-20 when the log task stalled on an event). reconstruct_trip.cpp, built against the
OLD judge (commit f9ad035, same rules as 0.3.1), picks per sample the frames with the least visible
evidence (mostly "not visible", only C or the sample's own state when needed) that make the old judge
reproduce the board's closed_ms peak. The new judge is then tested on those frames.

  python make_trip411_frames.py      (needs git + MinGW g++; writes trip411_frames.h)
"""
import json, os, subprocess, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
GXX = r"C:\ProgramData\mingw64\mingw64\bin\g++.exe"
OLD = "f9ad035"
E = {0: ".", 1: "O", 2: "C", 3: "u", 4: "."}   # 0 = Unknown (before the first frame) -> not visible

d = json.load(open(os.path.join(HERE, "trip411_samples.json")))
lines, prev = [], None
for s in d["samples"]:
    n = 7 if prev is None else max(1, round((s[1] - prev) / 150))
    prev = s[1]
    lines.append(f"{n} {E[s[2]]} {s[9]}")

with tempfile.TemporaryDirectory() as tmp:
    for f in ("drowsiness.cpp", "drowsiness.h", "drowsy_config.h", "domain_types.h"):
        src = subprocess.run(["git", "show", f"{OLD}:firmware/DrowsyFW/{f}"], cwd=HERE, check=True,
                             capture_output=True).stdout
        open(os.path.join(tmp, f), "wb").write(src)
    exe = os.path.join(tmp, "reconstruct.exe")
    subprocess.run([GXX, "-std=c++17", "-O2", "-I", tmp, os.path.join(HERE, "reconstruct_trip.cpp"),
                    os.path.join(tmp, "drowsiness.cpp"), "-o", exe], check=True)
    r = subprocess.run([exe], input="\n".join(lines) + "\n", capture_output=True, text=True, check=True)
    frames = r.stdout.strip()
    print(r.stderr.strip())

with open(os.path.join(HERE, "trip411_frames.h"), "w", newline="\n") as f:
    f.write("// generated by make_trip411_frames.py from trip411_samples.json - do not edit\n")
    f.write(f"// {len(d['samples'])} samples -> {len(frames)} frames of 150 ms - O open, C closed, u uncertain, . not visible\n")
    f.write("#pragma once\nstatic const char TRIP411_FRAMES[] =\n")
    for k in range(0, len(frames), 100):
        f.write(f'  "{frames[k:k + 100]}"\n')
    f.write(";\n")
print("wrote trip411_frames.h")
